package io.github.nxckywhxte.card.engine.core;

/**
 * Базовый интерфейс для любого объекта, участвующего в игре.
 *
 * <p>Это центральная абстракция ядра {@code engine-core}. Сущность может представлять собой что
 * угодно: карту, фишку, жетон, ресурс, здание, персонажа — движок не навязывает предметную область.
 *
 * <h3>Философия абстракции:</h3>
 *
 * <p>В отличие от наивных реализаций, где есть жёсткие классы {@code Card} с полями {@code suit} и
 * {@code rank}, наш подход полностью абстрактен:
 *
 * <ul>
 *   <li>Нет предопределённых полей (масть, ранг, стоимость и т.д.).
 *   <li>Разработчик игры сам определяет структуру сущности через наследование или систему атрибутов
 *       (будет добавлена в следующих версиях).
 *   <li>Это позволяет использовать движок для любых карточных и настольных игр: от классического
 *       "Дурака" до кастомных авторских механик.
 * </ul>
 *
 * <h3>Контракты и инварианты:</h3>
 *
 * <ul>
 *   <li>{@link #getEntityId()} должен возвращать <b>уникальный</b> идентификатор в рамках одной
 *       игровой сессии. Две разные сущности не могут иметь одинаковый ID.
 *   <li>Идентификатор должен быть <b>неизменяемым</b> на протяжении всей жизни сущности.
 *   <li>Сущности должны быть <b>неизменяемыми</b> (immutable) после создания. Изменение состояния
 *       игры происходит через перемещение сущностей между {@link Zone зонами}, а не через мутацию
 *       самих сущностей.
 * </ul>
 *
 * <h3>Примеры использования:</h3>
 *
 * <pre>{@code
 * // Пример 1: Карта в "Дураке"
 * public record PlayingCard(String id, String suit, int rank) implements Entity {}
 *
 * PlayingCard sixOfHearts = new PlayingCard("6H", "Hearts", 6);
 *
 * // Пример 2: Фишка в покере
 * public record PokerChip(String id, int value) implements Entity {}
 *
 * PokerChip chip100 = new PokerChip("chip-100", 100);
 *
 * // Пример 3: Ресурс в кастомной игре
 * public record ResourceToken(String id, String type, int amount) implements Entity {}
 *
 * ResourceToken wood = new ResourceToken("wood-1", "wood", 5);
 * }</pre>
 *
 * <h3>Связь с другими компонентами:</h3>
 *
 * <ul>
 *   <li>{@link Zone}: хранит коллекцию сущностей {@code Zone<E extends Entity>}.
 *   <li>{@link io.github.nxckywhxte.card.engine.core.Action}: оперирует сущностями (перемещает
 *       между зонами, проверяет атрибуты).
 *   <li>{@code engine-persistence}: сериализует сущности для сохранения в Event Store.
 * </ul>
 *
 * <h3>Расширение через атрибуты:</h3>
 *
 * <p>В будущих версиях {@code engine-core} будет добавлена система атрибутов (key-value хранилище),
 * позволяющая динамически расширять сущности без изменения интерфейса. Например:
 *
 * <pre>{@code
 * // Вместо жёсткого поля isTrump
 * entity.getAttribute("isTrump")  // возвращает Optional<Object>
 * }</pre>
 *
 * @author nxckywhxte
 * @since 0.1.0
 * @see Zone
 * @see Player
 */
public interface Entity {
  /**
   * Возвращает уникальный идентификатор сущности в рамках игровой сессии.
   *
   * <p>Идентификатор используется для:
   *
   * <ul>
   *   <li>Однозначной идентификации сущности в {@link Zone}.
   *   <li>Сериализации в {@code Event Sourcing} ({@code engine-persistence}).
   *   <li>Маршрутизации в сетевом слое ({@code engine-network}).
   *   <li>Логирования действий ({@code Action} оперирует ID сущностей).
   * </ul>
   *
   * <p><b>Контракт:</b> значение не может быть {@code null} или пустой строкой. Уникальность
   * гарантируется в рамках одной {@code GameSession}. Идентификатор должен быть неизменяемым.
   *
   * <p><b>Рекомендации по генерации ID:</b>
   *
   * <ul>
   *   <li>Для карт: используйте комбинацию масти и ранга (например, {@code "6H"} для шестёрки
   *       червей).
   *   <li>Для фишек/жетонов: используйте UUID или последовательные номера (например, {@code
   *       "chip-001"}).
   *   <li>Для динамически создаваемых сущностей: используйте {@code UUID.randomUUID()}.
   * </ul>
   *
   * @return уникальный идентификатор сущности (например, {@code "6H"}, {@code "chip-100"})
   */
  String getEntityId();
}
