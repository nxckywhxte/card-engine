package io.github.nxckywhxte.card.engine.core;

/**
 * Определяет семантику хранения и извлечения сущностей {@link Entity} из {@link Zone}.
 *
 * <p>Порядок задаётся при создании зоны и влияет на:
 *
 * <ul>
 *   <li>Внутреннюю структуру данных, используемую стандартной реализацией {@code StandardZone}.
 *   <li>Порядок элементов в списке, возвращаемом методом {@link Zone#getAllEntities()}.
 *   <li>Семантику операций "взять верхний элемент" или "взять первый элемент".
 * </ul>
 *
 * <p><b>Важно:</b> для зон с типом {@link #UNORDERED} порядок элементов определяется логикой
 * конкретной игры и не гарантируется движком.
 *
 * @author nxckywhxte
 * @since 0.1.0
 * @see Zone#getZoneOrder()
 */
public enum Order {
  /**
   * Стек — структура данных типа <b>LIFO</b> (Last In, First Out).
   *
   * <p>Сущности добавляются и извлекаются с одного конца ("сверху"). Последняя добавленная сущность
   * будет первой в списке {@link Zone#getAllEntities()} и первой извлечённой при стандартной
   * операции "взять".
   *
   * <p><b>Примеры использования:</b>
   *
   * <ul>
   *   <li>Колода для добора карт — берём верхнюю карту.
   *   <li>Сброс (отбой) — последняя сыгранная карта лежит сверху.
   *   <li>Стек действий в покере — последнее действие обрабатывается первым при разборе стека.
   * </ul>
   *
   * <p><b>Стандартная реализация:</b> {@code ArrayDeque} с добавлением и извлечением через {@code
   * push()}/{@code pop()}.
   */
  STACK,
  /**
   * Очередь — структура данных типа <b>FIFO</b> (First In, First Out).
   *
   * <p>Сущности добавляются в конец ("в хвост"), а извлекаются с начала ("из головы"). Первая
   * добавленная сущность будет первой в списке {@link Zone#getAllEntities()} и первой извлечённой.
   *
   * <p><b>Примеры использования:</b>
   *
   * <ul>
   *   <li>Рука игрока в некоторых механиках — первая взятая карта первой и играется.
   *   <li>Очередь ходов в пошаговых играх.
   *   <li>Буфер входящих действий при высокой нагрузке.
   * </ul>
   *
   * <p><b>Стандартная реализация:</b> {@code ArrayDeque} с добавлением через {@code addLast()} и
   * извлечением через {@code removeFirst()}.
   */
  QUEUE,
  /**
   * Неупорядоченное множество — коллекция без гарантированного порядка.
   *
   * <p>Порядок элементов в {@link Zone#getAllEntities()} не определён контрактом и может меняться
   * между вызовами. Разработчик игры не должен полагаться на порядок в таких зонах.
   *
   * <p><b>Примеры использования:</b>
   *
   * <ul>
   *   <li>Карты, лежащие на столе в момент взятки — важен состав, а не порядок.
   *   <li>Набор ресурсов в инвентаре.
   *   <li>Банк фишек, где важна только сумма.
   * </ul>
   *
   * <p><b>Стандартная реализация:</b> {@code LinkedHashSet} — сохраняет порядок добавления для
   * стабильности итерации, но не гарантирует семантику стека или очереди.
   */
  UNORDERED
}
