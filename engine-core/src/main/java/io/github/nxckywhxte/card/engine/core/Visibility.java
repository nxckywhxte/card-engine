package io.github.nxckywhxte.card.engine.core;

/**
 * Определяет уровень видимости содержимого {@link Zone} для различных участников игры.
 *
 * <p>Это ключевая концепция безопасности движка, реализующая принцип <b>Zero-Trust</b> ("нулевое
 * доверие"). Видимость задаётся один раз при создании зоны и используется модулем {@code
 * engine-network} для фильтрации данных перед отправкой клиенту через механизм <i>State
 * Projections</i>.
 *
 * <p><b>Важно:</b> само ядро ({@code engine-core}) не фильтрует данные на основе этого значения —
 * оно лишь хранит метаданные. Физическое отсечение приватной информации происходит на сетевом
 * уровне.
 *
 * <h3>Уровни видимости:</h3>
 *
 * <ul>
 *   <li>{@link #PUBLIC} — полное раскрытие для всех участников.
 *   <li>{@link #PRIVATE} — полное раскрытие только для владельца зоны.
 *   <li>{@link #PARTIAL} — избирательное раскрытие по атрибуту сущности.
 * </ul>
 *
 * @author nxckywhxte
 * @since 0.1.0
 * @see Zone#getZoneVisibility()
 * @see Zone#getOwner()
 */
public enum Visibility {
  /**
   * Публичная зона. Содержимое полностью видно всем игрокам и наблюдателям.
   *
   * <p><b>Примеры использования:</b>
   *
   * <ul>
   *   <li>Общий стол в покере или дураке — все видят сыгранные карты.
   *   <li>Банк фишек в казино-играх.
   *   <li>Общая колода в некоторых кооперативных играх.
   * </ul>
   *
   * <p>При проекции состояния для любого клиента все сущности зоны передаются полностью, со всеми
   * атрибутами.
   */
  PUBLIC,
  /**
   * Приватная зона. Содержимое полностью видно <b>только владельцу</b> зоны (определяется через
   * {@link Zone#getOwner()}).
   *
   * <p>Для всех остальных участников (включая наблюдателей, если не включён режим "God View") зона
   * выглядит как <i>чёрный ящик</i>: доступна только мета-информация — {@link Zone#zoneSize()}
   * размер и {@link Zone#getZoneName()} имя. Содержимое {@link Zone#getAllEntities()} полностью
   * скрывается.
   *
   * <p><b>Примеры использования:</b>
   *
   * <ul>
   *   <li>Рука игрока — классический пример приватной информации.
   *   <li>Закрытые карты в бридже или преферансе.
   *   <li>Скрытые ресурсы в стратегических играх.
   * </ul>
   *
   * <p><b>Контракт безопасности:</b> даже если злоумышленник перехватит сетевой трафик, в нём
   * физически не будет данных этой зоны для чужих игроков — фильтрация происходит на сервере.
   */
  PRIVATE,
  /**
   * Частично видимая зона. Все участники видят мета-данные зоны (размер, имя), но сами сущности
   * раскрываются избирательно.
   *
   * <p>Механизм фильтрации:
   *
   * <ol>
   *   <li>Проектор проходит по всем сущностям зоны.
   *   <li>Если у сущности установлен специальный атрибут-маркер (например, {@code "isRevealed"} со
   *       значением {@code true}) — она передаётся клиенту полностью.
   *   <li>Если маркера нет — сущность заменяется на "заглушку" (например, объект с ID {@code
   *       "CARD_BACK"} без остальных атрибутов).
   * </ol>
   *
   * <p><b>Примеры использования:</b>
   *
   * <ul>
   *   <li>Колода в дураке: все видят количество оставшихся карт, но только последняя карта (козырь)
   *       открыта.
   *   <li>Закрытые карты в пасьянсе, где часть из них постепенно открывается.
   *   <li>Инвентарь противника в RPG, где видны только слоты, но не предметы.
   * </ul>
   *
   * @implNote Конкретное имя атрибута-маркера ({@code "isRevealed"} или иное) определяется
   *     разработчиком игры и согласуется с реализацией {@code StateProjector} в модуле {@code
   *     engine-network}.
   */
  PARTIAL
}
